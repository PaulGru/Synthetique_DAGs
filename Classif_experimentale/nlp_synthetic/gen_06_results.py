"""
Standalone script: generates 06_results.png + 06_results.pdf (metrics table only)
for the 3 existing conf_varying_proxy experiments, from hardcoded final metrics.

Values read from existing 05_summary plots.
After a new training run, 06_results is auto-generated by main_nlp.py.
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'shared'))
from visualization_synth import plot_results_table

PLOT_BASE = os.path.join(os.path.dirname(__file__), 'plots')

# ── Hardcoded final metrics from the 3 existing 05_summary plots ──────────────
# Format: { split_key: [value] }  (list so hist[-1] works)
EXPERIMENTS = {
    'causal_sms_spam_conf_varying_proxy': {
        'erm': {'val_acc': [0.7410], 'test_acc': [0.7603]},
        'irm': {'val_acc': [0.6621], 'test_acc': [0.8648]},
    },
    'causal_agnews_conf_varying_proxy': {
        'erm': {'val_acc': [0.9252], 'test_acc': [0.1451]},
        'irm': {'val_acc': [0.7689], 'test_acc': [0.7002]},
    },
    'ac_sst2_conf_varying_proxy': {
        'erm': {'val_acc': [0.6648], 'test_acc': [0.7627]},
        'irm': {'val_acc': [0.6089], 'test_acc': [0.7583]},
    },
}

for exp_dir, metrics in EXPERIMENTS.items():
    out_dir = os.path.join(PLOT_BASE, exp_dir)
    if not os.path.isdir(out_dir):
        print(f'  Skipping {exp_dir}: directory not found')
        continue
    out_file = os.path.join(out_dir, '06_results.png')
    plot_results_table(metrics['erm'], metrics['irm'], out_file)
